/** `<Set>/<Name>.webp` (as cited in 8_Text.md) → asset for `next/image`. */
export function img(path: string): ImageAsset {
  const size = SIZES[path];
  if (!size) throw new Error(`Unknown image: ${path}`);
  return { src: `/images/${path}`, width: size[0], height: size[1] };
}

